const INK = 'var(--text-2)'
const ACC = 'var(--accent)'
const LINE = 'var(--line)'
const MUTE = 'var(--text-3)'

/* 圆角块 + 居中文字。
   fill 只接受当前色系的两种取法：'none' 或 'soft'（用 currentColor 的低透明度做底），
   不写 var(--bg-alt) —— SVG 作为独立文件或截图时拿不到站点变量，会退化成纯黑。 */
const chip = (x, y, w, h, label, opts = {}) => {
  const { accent = false, size = 13, fill = 'none', dash = false } = opts
  const paint = fill === 'soft' ? `fill="currentColor" fill-opacity="0.07"` : `fill="${fill}"`
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="8" ${paint} stroke="${accent ? ACC : LINE}" stroke-width="1.5"${dash ? ' stroke-dasharray="5 4"' : ''}/>
  <text x="${x + w / 2}" y="${y + h / 2 + size / 3}" text-anchor="middle" font-size="${size}" fill="${accent ? ACC : INK}">${label}</text>`
}

/* 横向箭头 */
const hArrow = (x1, x2, y) =>
  `<path d="M${x1} ${y} H${x2 - 7}" stroke="${LINE}" stroke-width="1.5"/>
  <polygon points="${x2},${y} ${x2 - 8},${y - 4} ${x2 - 8},${y + 4}" fill="${LINE}"/>`

/* 竖向箭头 */
const vArrow = (x, y1, y2) =>
  `<path d="M${x} ${y1} V${y2 - 7}" stroke="${LINE}" stroke-width="1.5"/>
  <polygon points="${x},${y2} ${x - 4},${y2 - 8} ${x + 4},${y2 - 8}" fill="${LINE}"/>`

const label = (x, y, text, opts = {}) => {
  const { size = 12, color = MUTE, anchor = 'start', weight = 400 } = opts
  return `<text x="${x}" y="${y}" font-size="${size}" fill="${color}" text-anchor="${anchor}" font-weight="${weight}">${text}</text>`
}

const frame = (inner, w = 720, h = 210) =>
  `<svg viewBox="0 0 ${w} ${h}" role="img" aria-hidden="true" xmlns="http://www.w3.org/2000/svg">${inner}</svg>`

